# 移動先タップ問題を図の全ての動きから作る分類（形そのものを覚えるもの）。ほかは大きな動き3つまで。
_全部の動きを問う分類 = ("フォーメーション", "ゾーン", "変則", "プレス")


def 戦術テンプレート() -> list[tuple[str, str, str, dict, list[dict]]]:
    """(種別, タイトル, 説明, 図データ, クイズ一覧)。タイトルの【】は分類（フォーメーション・セットプレーなど）。

    クイズ一覧＝基本の問題＋ポジション別・次の動き・位置タップの問題＋図から作る移動先タップ問題。
    """
    追加 = _ポジション別と次の動きの問題()
    結果 = []
    for 種別, タイトル, 説明, コマ一覧, クイズ in _オフェンスのテンプレート() + _ディフェンスのテンプレート():
        図 = {"frames": コマ一覧}
        問題 = [{**_問("", [], 0, ""), **q} for q in クイズ] + 追加.get(タイトル, [])
        上限 = None if re.match(rf"^【({'|'.join(_全部の動きを問う分類)})】", タイトル) else 3
        問題 += 戦術クイズ.移動先の問題を作る(図, 種別, 上限)
        結果.append((種別, タイトル, 説明, 図, 問題))
    return 結果


