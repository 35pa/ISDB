def _ドリルをつなぎ直す(接続先: sqlite3.Connection, 並び: list[int]) -> None:
    for 今, 次 in zip(並び, 並び[1:] + [None]):
        接続先.execute("UPDATE drill_steps SET next_step_id = ? WHERE id = ?", (次, 今))


def _ドリルを追加(接続先: sqlite3.Connection, チームID: int, カテゴリID: dict[str, int]) -> int:
    """標準ドリルのうち、同じスキルに同じ名前のドリルがないものを追加し、レベル順につなぎ直す。追加数を返す。"""
    既存 = {
        (行["category_id"], 行["title"]) for 行 in 接続先.execute("SELECT category_id, title FROM drill_steps WHERE team_id = ?", (チームID,)).fetchall()
    }
    追加分: dict[int, list[int]] = {}
    for カテゴリ, レベル, タイトル, 内容, 分, 条件 in ステップドリル:
        ID = カテゴリID[カテゴリ]
        if (ID, タイトル) in 既存:
            continue
        番号 = 接続先.execute(
            "SELECT COALESCE(MAX(step_no), 0) + 1 FROM drill_steps WHERE team_id = ? AND category_id = ? AND level = ?", (チームID, ID, レベル)
        ).fetchone()[0]
        追加分.setdefault(ID, []).append(
            接続先.execute(
                """INSERT INTO drill_steps (team_id, category_id, level, step_no, title, content, minutes, clear_condition)
                   VALUES (?, ?, ?, ?, ?, ?, ?, ?)""",
                (チームID, ID, レベル, 番号, タイトル, 内容, 分, 条件),
            ).lastrowid
        )
    for ID, 新規 in 追加分.items():
        ドリル = [dict(行) for 行 in 接続先.execute("SELECT * FROM drill_steps WHERE category_id = ? AND team_id = ?", (ID, チームID)).fetchall()]
        新規集合 = set(新規)
        # 今までの並びを保ったまま、レベル順（基礎→プロ）に並べる。新しいドリルは各レベルの後ろに入る
        並び = スキル診断.ドリルを段階順に並べる(d for d in ドリル if d["id"] not in 新規集合)
        新規ドリル = sorted((d for d in ドリル if d["id"] in 新規集合), key=lambda d: 新規.index(d["id"]))
        並び = sorted(並び + 新規ドリル, key=lambda d: スキル診断.レベル一覧.index(d["level"]))
        _ドリルをつなぎ直す(接続先, [d["id"] for d in 並び])
    return sum(len(v) for v in 追加分.values())


def _分類を除いた名前(タイトル: str) -> str:
    return re.sub(r"^【[^】]*】", "", タイトル).strip()


def _戦術を追加(接続先: sqlite3.Connection, チームID: int, 作成者ID: int | None) -> int:
    """標準の戦術テンプレートのうち、同じ名前（【分類】を除く）のものがないテンプレートを追加する。追加数を返す。"""
    時刻 = 現在時刻()
    既存 = {}
    for 行 in 接続先.execute("SELECT id, title, is_template FROM tactics WHERE team_id = ?", (チームID,)).fetchall():
        既存.setdefault(_分類を除いた名前(行["title"]), dict(行))
    追加数 = 0
    for 種別, タイトル, 説明, 図, クイズ一覧 in 戦術テンプレート():
        同名 = 既存.get(_分類を除いた名前(タイトル))
        if 同名:
            # 以前の標準テンプレート（分類なしの名前）は、分類つきの名前にそろえる
            if 同名["is_template"] and 同名["title"] == _分類を除いた名前(タイトル):
                接続先.execute("UPDATE tactics SET title = ? WHERE id = ?", (タイトル, 同名["id"]))
            continue
        カーソル = 接続先.execute(
            """INSERT INTO tactics (team_id, kind, title, description, data, is_template, published, created_by, created_at, updated_at)
               VALUES (?, ?, ?, ?, ?, 1, 1, ?, ?, ?)""",
            (チームID, 種別, タイトル, 説明, json.dumps(図, ensure_ascii=False), 作成者ID, 時刻, 時刻),
        )
        for クイズ in クイズ一覧:
            接続先.execute(
                "INSERT INTO tactic_quizzes (tactic_id, question, choices, answer_index, explanation) VALUES (?, ?, ?, ?, ?)",
                (カーソル.lastrowid, クイズ["question"], json.dumps(クイズ["choices"], ensure_ascii=False), クイズ["answer_index"], クイズ["explanation"]),
            )
        追加数 += 1
    return 追加数


def _カテゴリをそろえる(接続先: sqlite3.Connection, チームID: int) -> tuple[dict[str, int], int]:
    """標準のスキルカテゴリがなければ作る。{名前: ID} と追加数を返す。"""
    行一覧 = 接続先.execute("SELECT id, name FROM skill_categories WHERE team_id = ?", (チームID,)).fetchall()
    カテゴリID = {行["name"]: 行["id"] for 行 in 行一覧}
    追加数 = 0
    for 名前 in スキルカテゴリ:
        if 名前 not in カテゴリID:
            順番 = 接続先.execute("SELECT COALESCE(MAX(sort), -1) + 1 FROM skill_categories WHERE team_id = ?", (チームID,)).fetchone()[0]
            カテゴリID[名前] = 接続先.execute("INSERT INTO skill_categories (team_id, name, sort) VALUES (?, ?, ?)", (チームID, 名前, 順番)).lastrowid
            追加数 += 1
    # チームのスキルが標準のものだけなら、レーダーチャートの並びも標準の順にそろえる
    if set(カテゴリID) <= set(スキルカテゴリ):
        for 順番, 名前 in enumerate(スキルカテゴリ):
            接続先.execute("UPDATE skill_categories SET sort = ? WHERE id = ?", (順番, カテゴリID[名前]))
    return カテゴリID, 追加数


def 標準データを追加(接続先: sqlite3.Connection, チームID: int, 作成者ID: int | None = None) -> dict:
    """既存のチームに、足りない標準データ（スキル・ドリル・作戦テンプレート）を追加する。コーチが作ったデータは消さない。"""
    カテゴリID, カテゴリ数 = _カテゴリをそろえる(接続先, チームID)
    return {
        "categories": カテゴリ数,
        "drills": _ドリルを追加(接続先, チームID, カテゴリID),
        "tactics": _戦術を追加(接続先, チームID, 作成者ID),
    }


