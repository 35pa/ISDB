def _ハーフコート配置(オフェンス: list[tuple[int, int]], ディフェンス: list[tuple[int, int]] | None = None, ボール保持: int = 0) -> dict:
    選手 = [{"id": f"O{i + 1}", "team": "O", "label": str(i + 1), "x": x, "y": y} for i, (x, y) in enumerate(オフェンス)]
    for i, (x, y) in enumerate(ディフェンス or []):
        選手.append({"id": f"X{i + 1}", "team": "X", "label": str(i + 1), "x": x, "y": y})
    return {"players": 選手, "ball": f"O{ボール保持 + 1}", "lines": []}


def _線(種類: str, *点: tuple[int, int]) -> dict:
    return {"type": 種類, "points": [list(p) for p in 点]}


