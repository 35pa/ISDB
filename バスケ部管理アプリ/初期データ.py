def _コマ(味方: dict[str, tuple[float, float]], 相手: dict[str, tuple[float, float]] | None = None,
         ボール: str | None = "1", 線: tuple = (), 説明: str = "") -> dict:
    """味方・相手は {背番号: (x, y)}。ボールは味方の背番号（持っている人）。"""
    選手 = [{"id": f"O{番号}", "team": "O", "label": 番号, "x": x, "y": y} for 番号, (x, y) in 味方.items()]
    選手 += [{"id": f"X{番号}", "team": "X", "label": 番号, "x": x, "y": y} for 番号, (x, y) in (相手 or {}).items()]
    return {"players": 選手, "ball": f"O{ボール}" if ボール else None, "lines": list(線), "note": 説明}


def _線(種類: str, *点: tuple[float, float]) -> dict:
    return {"type": 種類, "points": [list(p) for p in 点]}


