def チームの初期データを投入(接続先: sqlite3.Connection, チームID: int, 作成者ID: int | None = None) -> None:
    時刻 = 現在時刻()
    カテゴリID = {}
    for 順番, 名前 in enumerate(スキルカテゴリ):
        カーソル = 接続先.execute(
            "INSERT INTO skill_categories (team_id, name, sort) VALUES (?, ?, ?)", (チームID, 名前, 順番)
        )
        カテゴリID[名前] = カーソル.lastrowid

    直前: dict[str, int] = {}
    ステップ番号: dict[tuple[str, str], int] = {}
    for カテゴリ, レベル, タイトル, 内容, 分, 条件 in ステップドリル:
        番号 = ステップ番号.get((カテゴリ, レベル), 0) + 1
        ステップ番号[(カテゴリ, レベル)] = 番号
        カーソル = 接続先.execute(
            """INSERT INTO drill_steps (team_id, category_id, level, step_no, title, content, minutes, clear_condition)
               VALUES (?, ?, ?, ?, ?, ?, ?, ?)""",
            (チームID, カテゴリID[カテゴリ], レベル, 番号, タイトル, 内容, 分, 条件),
        )
        if カテゴリ in 直前:
            接続先.execute("UPDATE drill_steps SET next_step_id = ? WHERE id = ?", (カーソル.lastrowid, 直前[カテゴリ]))
        直前[カテゴリ] = カーソル.lastrowid

    for 名前, 目的, 分, 道具, 分類, 説明 in 練習メニュー:
        接続先.execute(
            """INSERT INTO menus (team_id, name, purpose, minutes, equipment, category, description, created_at)
               VALUES (?, ?, ?, ?, ?, ?, ?, ?)""",
            (チームID, 名前, 目的, 分, 道具, 分類, 説明, 時刻),
        )

    for 種別, タイトル, 説明, 図, クイズ一覧 in 戦術テンプレート():
        カーソル = 接続先.execute(
            """INSERT INTO tactics (team_id, kind, title, description, data, is_template, published, created_by, created_at, updated_at)
               VALUES (?, ?, ?, ?, ?, 1, 1, ?, ?, ?)""",
            (チームID, 種別, タイトル, 説明, json.dumps(図, ensure_ascii=False), 作成者ID, 時刻, 時刻),
        )
        for クイズ in クイズ一覧:
            接続先.execute(
                "INSERT INTO tactic_quizzes (tactic_id, question, choices, answer_index, explanation) VALUES (?, ?, ?, ?, ?)",
                (カーソル.lastrowid, クイズ["question"], json.dumps(クイズ["choices"], ensure_ascii=False), クイズ["answer_index"], クイズ["explanation"]),
            )
